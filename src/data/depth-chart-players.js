export function pickThreeFrom(pool, exclude = []) {
  const filtered = pool.filter(p => !exclude.includes(p.name))
  const shuffled = [...filtered].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, 3)
}

export function pickThree(exclude = []) {
  return pickThreeFrom(QB_POOL, exclude)
}
