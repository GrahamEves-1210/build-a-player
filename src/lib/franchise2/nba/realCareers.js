// his whole career's totals: the real seasons and this league's (cur: the season under way, when it isn't on his rows
// yet). real: the totals are his true career (false: a veteran whose earlier seasons nobody has: don't print averages)
export function careerTotals(p, cur = null) {
  const base = realCareer(p)
  const t = { gp: 0, min: 0, pts: 0, reb: 0, ast: 0, stl: 0, blk: 0, tpm: 0 }
  if (base) for (const k of K) t[k] = base[k]
  for (const r of [...(p?.car ?? []), ...(cur ? [cur] : [])]) for (const k of K) t[k] += r[k] ?? 0
  return { ...t, base: !!base, whole: !!base || !predates(p) }
}
