// is he one of the real men the league opened with (not a made-up man, a build, or anyone drafted in the save)
const isReal = p => !!p && !!p.h && !p.gn && p.b == null && !((p.rk ?? 0) > REAL_THROUGH) && !((p.dr?.[0] ?? 0) > REAL_THROUGH + 1)
// his real career before the save: { y0, yrs, gp, min, pts, reb, ast, stl, blk, tpm }, or null (a made-up man, a rookie,
// a man the table lacks)
export function realCareer(p) {
  const r = isReal(p) ? REAL_CAREER[p.n] : null
  if (!r) return null
  const o = { y0: r[0], yrs: r[1] }
  K.forEach((k, j) => { o[k] = r[j + 2] })
  return o
}
