// Small copies of the NFL logos for a drawn coach's cap and chest (Franchise). A face is an SVG in an <img>, which
// can't fetch files, so each logo goes into the SVG as a data URI: this writes src/lib/franchise2/capLogos.js.
// The originals in public/logos/ are only read, never changed.
//   node scripts/franchise2/cap-logos.mjs [px=56]
import sharp from 'sharp'
import { readdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const SRC = join(ROOT, 'public', 'logos'), OUT = join(ROOT, 'src', 'lib', 'franchise2', 'capLogos.js')
const PX = Number(process.argv[2] ?? 56)
const teams = readdirSync(SRC).filter(f => /^[A-Z]{2,3}\.png$/.test(f)).map(f => f.slice(0, -4)).sort()
const rows = []
let total = 0
for (const t of teams) {
  // (trim the clear border so the logo fills its box, then fit it in PX x PX)
  // (a 16-colour palette png: at this size a third of a webp's bytes and just as clean)
  const img = sharp(join(SRC, `${t}.png`)).ensureAlpha().trim({ threshold: 1 }).resize(PX, PX, { fit: 'inside', kernel: 'lanczos3' })
  const { data, info } = await img.png({ palette: true, colours: 16, dither: 0.6, effort: 10, compressionLevel: 9 }).toBuffer({ resolveWithObject: true })
  // its main colour (the opaque pixels' average), so the drawing can tell when it would vanish on the cap's colour
  const raw = await sharp(data).ensureAlpha().raw().toBuffer()
  let r = 0, g = 0, b = 0, n = 0
  for (let i = 0; i < raw.length; i += 4) { const a = raw[i + 3] / 255; r += raw[i] * a; g += raw[i + 1] * a; b += raw[i + 2] * a; n += a }
  const avg = '#' + [r, g, b].map(v => Math.round(v / n).toString(16).padStart(2, '0')).join('')
  const uri = `data:image/png;base64,${data.toString('base64')}`
  total += uri.length
  rows.push(`  ${t}: ['${uri}', ${info.width}, ${info.height}, '${avg}'],`)
}
const head = `// GENERATED by scripts/franchise2/cap-logos.mjs from public/logos/*.png (${PX} px, png): do not edit.
// A drawn coach's team logo for his cap and chest: { TEAM: [data URI, width, height, its main colour] }
`
writeFileSync(OUT, `${head}export const CAP_LOGOS = {\n${rows.join('\n')}\n}\n`)
console.log(`${teams.length} logos, ${total} bytes of data URIs -> ${OUT}`)
