#!/usr/bin/env node
// Fetches jersey numbers for all NBA players from ESPN API
// Run: node scripts/fetch-nba-numbers.mjs

import { writeFileSync } from 'fs'
import { join } from 'path'

const SHORT_MAP = {
  'Atlanta Hawks':'ATL','Boston Celtics':'BOS','Brooklyn Nets':'BKN',
  'Charlotte Hornets':'CHA','Chicago Bulls':'CHI','Cleveland Cavaliers':'CLE',
  'Dallas Mavericks':'DAL','Denver Nuggets':'DEN','Detroit Pistons':'DET',
  'Golden State Warriors':'GSW','Houston Rockets':'HOU','Indiana Pacers':'IND',
  'LA Clippers':'LAC','Los Angeles Clippers':'LAC','Los Angeles Lakers':'LAL',
  'Memphis Grizzlies':'MEM','Miami Heat':'MIA','Milwaukee Bucks':'MIL',
  'Minnesota Timberwolves':'MIN','New Orleans Pelicans':'NOP',
  'New York Knicks':'NYK','Oklahoma City Thunder':'OKC','Orlando Magic':'ORL',
  'Philadelphia 76ers':'PHI','Phoenix Suns':'PHX','Portland Trail Blazers':'POR',
  'Sacramento Kings':'SAC','San Antonio Spurs':'SAS','Toronto Raptors':'TOR',
  'Utah Jazz':'UTA','Washington Wizards':'WAS',
}

const teamsRes = await fetch('https://site.web.api.espn.com/apis/site/v2/sports/basketball/nba/teams?limit=32')
const teamsData = await teamsRes.json()
const teams = teamsData.sports[0].leagues[0].teams.map(t => ({
  id: t.team.id,
  name: t.team.displayName,
  short: SHORT_MAP[t.team.displayName] ?? t.team.abbreviation,
}))

console.log(`Found ${teams.length} teams`)

const numbers = {}

for (const team of teams) {
  const url = `https://site.api.espn.com/apis/site/v2/sports/basketball/nba/teams/${team.id}/roster`
  const res = await fetch(url)
  if (!res.ok) { console.error(`FAILED ${team.short}: ${res.status}`); continue }
  const data = await res.json()
  const athletes = data.athletes ?? []
  const players = athletes.flatMap(g => g.items ?? g.athletes ?? [g]).filter(p => p?.fullName)
  for (const p of players) {
    if (p.jersey) numbers[p.fullName] = parseInt(p.jersey, 10)
  }
  console.log(`✓ ${team.short.padEnd(4)} — ${players.length} players`)
}

const lines = Object.entries(numbers)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, num]) => `  ${JSON.stringify(name)}: ${num},`)
  .join('\n')

const content = `// Auto-generated by scripts/fetch-nba-numbers.mjs\nexport const NBA_JERSEY_NUMBERS = {\n${lines}\n}\n`
const outPath = join(process.cwd(), 'src', 'data', 'nba-jersey-numbers.js')
writeFileSync(outPath, content, 'utf8')
console.log(`\nWrote ${Object.keys(numbers).length} jersey numbers to src/data/nba-jersey-numbers.js`)
