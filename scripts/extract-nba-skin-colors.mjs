#!/usr/bin/env node
// Extracts skin tone from each player's headshot photo.
// Samples the face region, filters to flesh-tone pixels, averages them.

import { readFileSync, writeFileSync } from 'fs'
import { join } from 'path'
import { createRequire } from 'module'

const require = createRequire(import.meta.url)
const { Jimp } = require('jimp')

const headshotsDir  = join(process.cwd(), 'public', 'headshots', 'nba')
const headshotsJson = JSON.parse(readFileSync(join(process.cwd(), 'src', 'data', 'nba-headshots.json'), 'utf8'))

function toHex(r, g, b) {
  return '#' + [r, g, b].map(v => v.toString(16).padStart(2, '0')).join('')
}

function decodePixel(int32) {
  return {
    r: (int32 >> 24) & 0xFF,
    g: (int32 >> 16) & 0xFF,
    b: (int32 >> 8)  & 0xFF,
  }
}

function isSkinTone(r, g, b) {
  if (r < 60) return false                   // too dark
  if (r < g || r < b) return false           // red must dominate
  if (g < b * 0.5) return false              // too much blue vs green
  const max = Math.max(r, g, b)
  const min = Math.min(r, g, b)
  if (min > 210 && max - min < 25) return false  // near-white background
  const sat = max === 0 ? 0 : (max - min) / max
  if (sat < 0.06) return false               // too grey
  if (sat > 0.80) return false               // too saturated (jersey)
  return true
}

async function extractSkinColor(imagePath) {
  try {
    const img = await Jimp.read(imagePath)
    const w = img.bitmap.width
    const h = img.bitmap.height

    // Sample face region: x 20-80%, y 5-55%
    const x0 = Math.floor(w * 0.20), x1 = Math.floor(w * 0.80)
    const y0 = Math.floor(h * 0.05), y1 = Math.floor(h * 0.55)

    let rSum = 0, gSum = 0, bSum = 0, count = 0
    for (let y = y0; y < y1; y += 3) {
      for (let x = x0; x < x1; x += 3) {
        const { r, g, b } = decodePixel(img.getPixelColor(x, y))
        if (isSkinTone(r, g, b)) { rSum += r; gSum += g; bSum += b; count++ }
      }
    }

    if (count < 8) return null
    return toHex(Math.round(rSum / count), Math.round(gSum / count), Math.round(bSum / count))
  } catch {
    return null
  }
}

const result = {}
const entries = Object.entries(headshotsJson)
let done = 0

for (const [name, id] of entries) {
  const imgPath = join(headshotsDir, `${id}.jpg`)
  try { readFileSync(imgPath) } catch { done++; continue }

  const color = await extractSkinColor(imgPath)
  if (color) result[name] = color
  done++
  if (done % 50 === 0) process.stdout.write(`\r${done}/${entries.length}  (${Object.keys(result).length} found)`)
}

console.log(`\nExtracted skin colors for ${Object.keys(result).length}/${entries.length} players`)

const lines = Object.entries(result)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, color]) => `  ${JSON.stringify(name)}: '${color}',`)
  .join('\n')

const content = `// Auto-generated by scripts/extract-nba-skin-colors.mjs\nexport const NBA_SKIN_COLORS = {\n${lines}\n}\n`
writeFileSync(join(process.cwd(), 'src', 'data', 'nba-skin-colors.js'), content, 'utf8')
console.log('Wrote src/data/nba-skin-colors.js')
