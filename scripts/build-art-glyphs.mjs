// The app's team badges and jersey numbers (lib/teamBadge.js, lib/jerseyArt.js) are drawn as paths: an <img> of an
// SVG can't load a font. This turns the few characters they need from three open fonts (SIL OFL, in
// scripts/art-fonts with their licences) into path data and writes src/lib/artGlyphs.js. Run from the repo root:
//   npm i --no-save opentype.js@1.3.4 && node scripts/build-art-glyphs.mjs
// Only rerun to change a font: the output is committed.
//   mono  Anton     the badges' monogram (the app's own display face)
//   num   Graduate  a jersey's number, collegiate block (made heavier when drawn: lib/artType.js)
//   soc   Russo One a football club's or a nation's number
import opentype from 'opentype.js'
import { writeFileSync } from 'fs'

const SETS = {
  mono: ['Anton-Regular', 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789&'],
  num: ['Graduate-Regular', '0123456789'],
  varsity: ['Graduate-Regular', 'ABCDEFGHIJKLMNOPQRSTUVWXYZ&'],
  soc: ['RussoOne-Regular', '0123456789'],
}
const r = n => Math.round(n * 10) / 10
const out = {}
for (const [name, [file, chars]] of Object.entries(SETS)) {
  const font = opentype.loadSync(`scripts/art-fonts/${file}.ttf`)
  const k = 100 / font.unitsPerEm
  // every glyph on one scale: 100 to the em, the baseline at 0, the cap height measured from H (or 0)
  const capG = font.charToGlyph(chars.includes('H') ? 'H' : '0').getBoundingBox()
  const g = {}
  for (const ch of chars) {
    const gl = font.charToGlyph(ch)
    const p = gl.getPath(0, 0, 100)
    let at = ''
    const d = p.commands.map(c => {
      // (a line to where the pen already is: dropped)
      if (c.type === 'L' && at === r(c.x) + ' ' + r(c.y)) return ''
      if (c.x != null) at = r(c.x) + ' ' + r(c.y)
      if (c.type === 'M' || c.type === 'L') return c.type + r(c.x) + ' ' + r(c.y)
      if (c.type === 'Q') return 'Q' + [c.x1, c.y1, c.x, c.y].map(r).join(' ')
      if (c.type === 'C') return 'C' + [c.x1, c.y1, c.x2, c.y2, c.x, c.y].map(r).join(' ')
      return 'Z'
    }).join('').replace(/ -/g, '-')
    const bb = gl.getBoundingBox()
    g[ch] = [r(gl.advanceWidth * k), r(bb.x1 * k), r(bb.x2 * k), d]
  }
  out[name] = { cap: r(capG.y2 * k), g }
}
const body = `// Generated by scripts/build-art-glyphs.mjs from SIL OFL fonts (scripts/art-fonts): do not edit.
// set → { cap: cap height, g: { char: [advance, left, right, path] } }, 100 units to the em, baseline at y 0
export default ${JSON.stringify(out)}
`
writeFileSync('src/lib/artGlyphs.js', body)
console.log('artGlyphs:', Object.entries(out).map(([k, v]) => `${k} ${Object.keys(v.g).length}`).join(', '), (body.length / 1024).toFixed(1) + ' KB')
