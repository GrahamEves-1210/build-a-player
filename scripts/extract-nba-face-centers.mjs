#!/usr/bin/env node
// For each NBA headshot, finds the centroid of skin-tone pixels
// to determine where the face actually sits within the photo.
// Outputs cx_pct / cy_pct (0-100) used as CSS object-position.

import { readFileSync, writeFileSync } from 'fs'
import { join } from 'path'
import { createRequire } from 'module'

const require = createRequire(import.meta.url)
const { Jimp } = require('jimp')

const headshotsDir  = join(process.cwd(), 'public', 'headshots', 'nba')
const headshotsJson = JSON.parse(readFileSync(join(process.cwd(), 'src', 'data', 'nba-headshots.json'), 'utf8'))

function decodePixel(int32) {
  return { r: (int32 >> 24) & 0xFF, g: (int32 >> 16) & 0xFF, b: (int32 >> 8) & 0xFF }
}

function isSkinTone(r, g, b) {
  if (r < 60) return false
  if (r < g || r < b) return false
  if (g < b * 0.5) return false
  const max = Math.max(r, g, b), min = Math.min(r, g, b)
  if (min > 210 && max - min < 25) return false
  const sat = max === 0 ? 0 : (max - min) / max
  if (sat < 0.06 || sat > 0.80) return false
  return true
}

async function getFaceCenter(imagePath) {
  try {
    const img = await Jimp.read(imagePath)
    const w = img.bitmap.width
    const h = img.bitmap.height

    // Search upper 65% of image for face
    const y1 = Math.floor(h * 0.65)

    let xSum = 0, ySum = 0, count = 0
    for (let y = 0; y < y1; y += 2) {
      for (let x = 0; x < w; x += 2) {
        const { r, g, b } = decodePixel(img.getPixelColor(x, y))
        if (isSkinTone(r, g, b)) { xSum += x; ySum += y; count++ }
      }
    }

    if (count < 8) return null

    return {
      cx: Math.round((xSum / count) / w * 100),
      cy: Math.round((ySum / count) / h * 100),
    }
  } catch {
    return null
  }
}

const result = {}
const entries = Object.entries(headshotsJson)
let done = 0

for (const [name, id] of entries) {
  const imgPath = join(headshotsDir, `${id}.jpg`)
  try { readFileSync(imgPath) } catch { done++; continue }

  const center = await getFaceCenter(imgPath)
  if (center) result[name] = center
  done++
  if (done % 50 === 0) process.stdout.write(`\r${done}/${entries.length}  (${Object.keys(result).length} found)`)
}

console.log(`\nFound face centers for ${Object.keys(result).length}/${entries.length} players`)

const lines = Object.entries(result)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, { cx, cy }]) => `  ${JSON.stringify(name)}: [${cx},${cy}],`)
  .join('\n')

const content = `// Auto-generated by scripts/extract-nba-face-centers.mjs\n// [cx_pct, cy_pct] — face centroid as % of image, used as CSS object-position\nexport const NBA_FACE_CENTERS = {\n${lines}\n}\n`
writeFileSync(join(process.cwd(), 'src', 'data', 'nba-face-centers.js'), content, 'utf8')
console.log('Wrote src/data/nba-face-centers.js')
